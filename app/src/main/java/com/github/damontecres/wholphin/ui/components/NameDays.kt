object NameDays {
    /**
     * The names having their name day on [date] or null if nobody has it on that day
     */
    fun forDate(date: LocalDate): String? = forDay(date.monthValue, date.dayOfMonth)

    /**
     * The names having their name day on [day]. [month] (both 1-based) or null if nobody has it
     */
    fun forDay(
        month: Int,
        day: Int,
    ): String? =
        table
            .getOrNull(month - 1)
            ?.getOrNull(day - 1)
            ?.takeIf { it.isNotEmpty() }

